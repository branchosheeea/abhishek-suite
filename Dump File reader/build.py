"""Build "ME Dump Viewer.html": src/index.html with its CSS and scripts inlined.

The result is one file that opens by double-click, works offline and can be
emailed. Edit the files in src/, then run:  python build.py
"""
from __future__ import annotations

import re
import sys
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
OUT = HERE / "ME Dump Viewer.html"


def inline(html: str) -> str:
    def css(match: re.Match[str]) -> str:
        text = (SRC / match.group(1)).read_text(encoding="utf-8")
        return "<style>\n" + text + "\n</style>"

    def script(match: re.Match[str]) -> str:
        text = (SRC / match.group(1)).read_text(encoding="utf-8")
        if "</script" in text.lower():
            raise SystemExit(f"{match.group(1)} contains '</script', which would end the inline script early.")
        return "<script>\n" + text + "\n</script>"

    html, n_css = re.subn(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    html, n_js = re.subn(r'<script src="([^"]+)"></script>', script, html)
    if n_css != 1 or n_js != 4:
        raise SystemExit(f"Expected 1 stylesheet and 4 scripts in src/index.html, found {n_css} and {n_js}.")
    return html


def main() -> int:
    html = (SRC / "index.html").read_text(encoding="utf-8")
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    banner = f"<!-- ME Dump Viewer, built {stamp} from src/. Edit src/ and run build.py; do not edit this file. -->\n"
    out = inline(html).replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name} ({OUT.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
