"""Short-lived signed tickets for the local web workspaces.

Format (identical in the Node apps, lib/server/auth.ts):  nv1.<b64url(json payload)>.<b64url(HMAC-SHA256)>
where the HMAC covers the ASCII text "nv1.<b64url(json payload)>". Payload:
    {typ: "enter"|"service"|"session", aud: "sir"|"evi", sub, name, adm, grants, iat, exp, jti}
The secret is per web server run (generated by the launcher, passed to the server in its environment).
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import secrets as _secrets
import time

PREFIX = "nv1"
TYPES = ("enter", "service", "session")
AUDIENCES = ("sir", "evi")


class TicketError(ValueError):
    pass


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def unb64url(text: str) -> bytes:
    pad = "=" * (-len(text) % 4)
    try:
        return base64.urlsafe_b64decode(text + pad)
    except (ValueError, TypeError) as error:
        raise TicketError("malformed ticket") from error


def new_secret() -> str:
    """64 hex characters (32 random bytes)."""
    return _secrets.token_hex(32)


def _key(secret: str) -> bytes:
    if len(secret) < 64:
        raise TicketError("secret too short")
    return secret.encode("ascii")


def mint(secret: str, typ: str, aud: str, sub: str, *, name: str = "", adm: bool = False, grants: list[dict] | None = None,
         ttl: int = 120, now: float | None = None, jti: str | None = None) -> str:
    if typ not in TYPES or aud not in AUDIENCES:
        raise TicketError("unknown ticket type or audience")
    issued = int(now if now is not None else time.time())
    payload = {"typ": typ, "aud": aud, "sub": sub, "name": name, "adm": bool(adm), "grants": grants or [],
               "iat": issued, "exp": issued + int(ttl), "jti": jti or _secrets.token_hex(8)}
    body = f"{PREFIX}.{b64url(json.dumps(payload, separators=(',', ':'), ensure_ascii=False).encode('utf-8'))}"
    mac = hmac.new(_key(secret), body.encode("ascii"), hashlib.sha256).digest()
    return f"{body}.{b64url(mac)}"


def verify(secret: str, token: str, typ: str, aud: str, now: float | None = None) -> dict:
    parts = (token or "").split(".")
    if len(parts) != 3 or parts[0] != PREFIX:
        raise TicketError("malformed ticket")
    expected = hmac.new(_key(secret), f"{parts[0]}.{parts[1]}".encode("ascii"), hashlib.sha256).digest()
    if not hmac.compare_digest(expected, unb64url(parts[2])):
        raise TicketError("bad signature")
    try:
        payload = json.loads(unb64url(parts[1]).decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as error:
        raise TicketError("malformed payload") from error
    if not isinstance(payload, dict) or payload.get("typ") != typ or payload.get("aud") != aud:
        raise TicketError("wrong ticket type or audience")
    current = int(now if now is not None else time.time())
    if not isinstance(payload.get("exp"), int) or payload["exp"] < current:
        raise TicketError("expired")
    if not isinstance(payload.get("sub"), str) or not payload["sub"]:
        raise TicketError("no subject")
    return payload
